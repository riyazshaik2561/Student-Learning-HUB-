const BASE = process.env.AI_BASE_URL;
const KEY = process.env.AI_API_KEY;
const MODEL = process.env.AI_MODEL || 'gpt-4o-mini';
async function askAI({system, prompt}) {
  if (!BASE || !KEY) return { mode: 'rules-based-fallback', text: fallback(prompt) };
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 18000);
  try {
    const response = await fetch(`${BASE.replace(/\/$/, '')}/chat/completions`, {
      method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${KEY}` },
      body: JSON.stringify({ model: MODEL, temperature: 0.4, max_tokens: 700, messages: [{role:'system',content:system},{role:'user',content:prompt}] }), signal: controller.signal
    });
    if (!response.ok) throw new Error(`AI provider returned ${response.status}`);
    const data = await response.json(); const text = data?.choices?.[0]?.message?.content;
    if (typeof text !== 'string' || !text.trim()) throw new Error('AI provider returned an empty response');
    return { mode: 'live-ai', text: text.trim() };
  } catch (error) {
    return { mode: 'rules-based-fallback', text: fallback(prompt), note: 'The AI provider was unavailable; this is a local fallback response.' };
  } finally { clearTimeout(timer); }
}
function fallback(prompt='') {
 const p = String(prompt).toLowerCase();
 if (p.includes('ohm') || p.includes('resistance')) return 'Use Ohm’s Law: current (I) = voltage (V) ÷ resistance (R). Increasing voltage increases current when resistance stays fixed; increasing resistance reduces current when voltage stays fixed. Try changing one variable at a time and record what changes.';
 if (p.includes('sql') || p.includes('query')) return 'Start by naming the columns you need in SELECT, choose the source table with FROM, then narrow the rows with WHERE. Test a simple query first, and add JOIN or GROUP BY only when you can explain why it is needed.';
 if (p.includes('career') || p.includes('developer')) return 'Build evidence in small steps: strengthen programming fundamentals, practice SQL and data structures, then complete a project you can explain clearly. Track each skill as self-reported or supported by a completed assessment so your roadmap stays honest.';
 return 'Let’s break this into manageable steps. First, identify the concept you are trying to understand. Next, work through one small example, explain why each step is valid, and then try a similar question without looking at the solution. This response is generated by the local fallback, not a live AI model.';
}
module.exports = { askAI };
